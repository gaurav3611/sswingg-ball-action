/*
  Builds src/components/icon-data.ts: the shapes of the icons the app draws.

    node tools/icons.mjs

  The shapes come from the lucide-static package, a development dependency that is not part
  of the app. Only the icons named below are copied. This is the same method, and the same
  icon style, as the SSwinGG web app (angular-cricket-frontend/tools/icons.mjs).
  The cricket bat is not in Lucide, so it is drawn here on the same 24 unit grid.

  To add an icon: add its Lucide name to NAMES, run this, and use <Icon name="..." />.
  Lucide's licence is copied to licenses/lucide.txt.
*/
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const LUCIDE = join(PROJECT, 'node_modules', 'lucide-static');
const OUT = join(PROJECT, 'src', 'components', 'icon-data.ts');

const NAMES = [
  'activity', 'arrow-left', 'arrow-right', 'calendar-days', 'camera', 'chart-line', 'check',
  'chevron-left', 'chevron-right', 'circle-check', 'circle-x', 'clock', 'download', 'eye',
  'eye-off', 'flag', 'gauge', 'house', 'info', 'lightbulb', 'lock', 'log-out', 'mail', 'minus',
  'pause', 'play', 'plus', 'rotate-ccw', 'ruler', 'scissors', 'settings', 'shield-check',
  'smartphone', 'square', 'step-back', 'step-forward', 'target', 'trash', 'triangle-exclamation-point',
  'user', 'users', 'video', 'x',
];

/** Drawn for this app: the blade runs from bottom left, the handle to the top right, a ball beside it. */
const OWN = {
  bat: [
    ['path', { d: 'M7 21 3 17l9-9 4 4Z' }],
    ['path', { d: 'm14 10 6-6' }],
    ['circle', { cx: '18.5', cy: '18.5', r: '2.5' }],
  ],
};

const SHAPE_KEYS = { path: ['d'], circle: ['cx', 'cy', 'r'], rect: ['x', 'y', 'width', 'height', 'rx'] };

const lucide = JSON.parse(readFileSync(join(LUCIDE, 'icon-nodes.json'), 'utf8'));
const version = JSON.parse(readFileSync(join(LUCIDE, 'package.json'), 'utf8')).version;

const icons = {};
for (const name of NAMES) {
  if (!lucide[name]) throw new Error(`Lucide ${version} has no icon named "${name}"`);
  icons[name] = lucide[name];
}
Object.assign(icons, OWN);

const lines = Object.keys(icons).sort().map((name) => {
  const shapes = icons[name].map(([tag, attrs]) => {
    const keys = SHAPE_KEYS[tag];
    if (!keys) throw new Error(`Icon "${name}" uses <${tag}>, which Icon cannot draw yet. Add it to SHAPE_KEYS here and to icon.tsx.`);
    const extra = Object.keys(attrs).filter((k) => !keys.includes(k) && !(tag === 'rect' && k === 'ry'));
    if (extra.length) throw new Error(`Icon "${name}": <${tag}> has attributes this tool does not copy: ${extra.join(', ')}`);
    const fields = keys.filter((k) => attrs[k] !== undefined).map((k) => `${k}: ${JSON.stringify(String(attrs[k]))}`);
    return `{ tag: ${JSON.stringify(tag)}, ${fields.join(', ')} }`;
  });
  return `  ${JSON.stringify(name)}: [\n${shapes.map((s) => '    ' + s + ',').join('\n')}\n  ],`;
});

writeFileSync(OUT, `// Generated by tools/icons.mjs. Do not edit by hand: change the list there and run it again.
// Shapes from Lucide ${version} (https://lucide.dev), ISC licence, see licenses/lucide.txt.
// "bat" was drawn for this app.

export type IconShape =
  | { tag: 'path'; d: string }
  | { tag: 'circle'; cx: string; cy: string; r: string }
  | { tag: 'rect'; x: string; y: string; width: string; height: string; rx?: string };

export const ICONS = {
${lines.join('\n')}
} satisfies Record<string, IconShape[]>;

export type IconName = keyof typeof ICONS;
`);

mkdirSync(join(PROJECT, 'licenses'), { recursive: true });
copyFileSync(join(LUCIDE, 'LICENSE'), join(PROJECT, 'licenses', 'lucide.txt'));
console.log(`wrote ${Object.keys(icons).length} icons to ${OUT}`);
